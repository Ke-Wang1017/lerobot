@dataclass
class DatasetRecordConfig:
    # Dataset identifier. By convention it should match '{hf_username}/{dataset_name}' (e.g. `lerobot/test`).
    repo_id: str
    # A short but accurate description of the task performed during the recording (e.g. "Pick the Lego block and drop it in the box on the right.")
    single_task: str
    # Root directory where the dataset will be stored (e.g. 'dataset/path'). If None, defaults to $HF_LEROBOT_HOME/repo_id.
    root: str | Path | None = None
    # Limit the frames per second.
    fps: int = 30
    # Number of seconds for data recording for each episode.
    episode_time_s: int | float = 60
    # Number of seconds for resetting the environment after each episode.
    reset_time_s: int | float = 60
    # Number of episodes to record.
    num_episodes: int = 50
    # Encode frames in the dataset into video
    video: bool = True
    # Record images to the dataset (set False to save parquet only, skipping image/video recording)
    record_images: bool = True
    # Upload dataset to Hugging Face hub.
    push_to_hub: bool = True
    # Upload on private repository on the Hugging Face hub.
    private: bool = False
    # Add tags to your dataset on the hub.
    tags: list[str] | None = None
    # Number of subprocesses handling the saving of frames as PNG. Set to 0 to use threads only;
    # set to ≥1 to use subprocesses, each using threads to write images. The best number of processes
    # and threads depends on your system. We recommend 4 threads per camera with 0 processes.
    # If fps is unstable, adjust the thread count. If still unstable, try using 1 or more subprocesses.
    num_image_writer_processes: int = 0
    # Number of threads writing the frames as png images on disk, per camera.
    # Too many threads might cause unstable teleoperation fps due to main thread being blocked.
    # Not enough threads might cause low camera fps.
    num_image_writer_threads_per_camera: int = 4
    # Number of episodes to record before batch encoding videos
    # Set to 1 for immediate encoding (default behavior), or higher for batched encoding
    video_encoding_batch_size: int = 1
    # RGB video encoder config (codec, preset, extra options). Override per-field on the
    # CLI, e.g. --dataset.rgb_encoder.vcodec=h264. See lerobot.configs.video.
    rgb_encoder: RGBEncoderConfig = field(default_factory=rgb_encoder_defaults)
    # Depth video encoder config (used for depth-map features).
    depth_encoder: DepthEncoderConfig = field(default_factory=depth_encoder_defaults)
    # Enable streaming video encoding: encode frames in real-time during capture instead
    # of writing PNG images first. Makes save_episode() near-instant. More info in the documentation: https://huggingface.co/docs/lerobot/streaming_video_encoding
    streaming_encoding: bool = False
    # Maximum number of frames to buffer per camera when using streaming encoding.
    # ~1s buffer at 30fps. Provides backpressure if the encoder can't keep up.
    encoder_queue_maxsize: int = 30
    # Number of threads per encoder instance. None = auto (codec default).
    # Lower values reduce CPU usage, maps to 'lp' (via svtav1-params) for libsvtav1 and 'threads' for h264/hevc..
    encoder_threads: int | None = None
    # Rename map for the observation to override the image and state keys
    rename_map: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if self.single_task is None:
            raise ValueError("You need to provide a task as argument in `single_task`.")


@dataclass
class RecordConfig:
    robot: RobotConfig
    dataset: DatasetRecordConfig
    # Whether to control the robot with a teleoperator
    teleop: TeleoperatorConfig | None = None
    # Whether to control the robot with a policy
    policy: PreTrainedConfig | None = None
    # Display all cameras on screen
    display_data: bool = False
    # Visualization backend used when display_data is True: "rerun" or "foxglove".
    display_mode: str = "rerun"
    # For "rerun": IP of a remote server to send to. For "foxglove": interface to bind the WebSocket
    # server to (127.0.0.1 for local only, 0.0.0.0 for all interfaces).
    display_ip: str | None = None
    # For "rerun": port of the remote server. For "foxglove": port to bind the WebSocket server to.
    display_port: int | None = None
    # Whether to display compressed (JPEG) images instead of raw frames
    display_compressed_images: bool = False
    # Use vocal synthesis to read events.
    play_sounds: bool = True
    # Resume recording on an existing dataset.
    resume: bool = False
    # Optional: Record intervention-only fragments to a separate correction dataset.
    # Each intervention fragment becomes a separate episode in this dataset.
    intervention_repo_id: str | None = None
    # Start with a reset phase before the first episode to allow setting up the environment.
    start_with_reset: bool = True
    # Action interpolation multiplier for smoother policy control (1=off, 2=2x, 3=3x)
    # Only applies when using a policy (not teleop)
    interpolation_multiplier: int = 1
    # Latency monitoring: capture per-stage timing into an in-memory aggregator
    # and publish a JSON snapshot for the GUI to read. Mirrors the teleop flag.
    # See src/lerobot/gui/docs/latency_monitoring.md.
    latency_monitor: bool = False
    # Where to write latency_snapshot.json (when --latency_monitor=true)
    # AND the per-run log file. Distinct from teleop's "outputs/teleop"
    # so the GUI latency dashboard treats record as its own source key
    # (LATENCY_SOURCES["record"]) and doesn't double-render the panel.
    latency_output_dir: str = "outputs/record"
    # Duration (seconds) of the programmatic ramp-to-start for file-backed
    # teleops (e.g. trajectory_replay) during the auto-reset phase between
    # episodes. Short by default since this is robot-driven, not human-driven.
    auto_reset_duration_s: float = 3.0

    def __post_init__(self):
        # HACK: We parse again the cli args here to get the pretrained path if there was one.
        policy_path = parser.get_path_arg("policy")

        if policy_path:
            cli_overrides = parser.get_cli_overrides("policy")

            self.policy = PreTrainedConfig.from_pretrained(policy_path, cli_overrides=cli_overrides)
            self.policy.pretrained_path = policy_path

        if self.teleop is None and self.policy is None:
            raise ValueError("Choose a policy, a teleoperator or both to control the robot")

    @classmethod
    def __get_path_fields__(cls) -> list[str]:
        """This enables the parser to load config from the policy using `--policy.path=local/dir`"""
        return ["policy"]


""" --------------- record_loop() data flow --------------------------
       [ Robot ]
           V
     [ robot.get_observation() ] ---> raw_obs
           V
     [ robot_observation_processor ] ---> processed_obs
           V
     .-----( ACTION LOGIC )------------------.
     V                                       V
     [ From Teleoperator ]                   [ From Policy ]
     |                                       |
     |  [teleop.get_action] -> raw_action    |   [predict_action]
     |          |                            |          |
     |          V                            |          V
     | [teleop_action_processor]             |          |
     |          |                            |          |
     '---> processed_teleop_action           '---> processed_policy_action
     |                                       |
     '-------------------------.-------------'
                               V
                  [ robot_action_processor ] --> robot_action_to_send
                               V
                    [ robot.send_action() ] -- (Robot Executes)
                               V
                    ( Save to Dataset )
                               V
                  ( Rerun Log / Loop Wait )
"""


def _write_episode_health(
    latency_session: LatencySession,
    dataset: LeRobotDataset,
    episode_index: int,
    fps: int,
) -> None:
    """Compute and persist quality stats for a just-saved episode.

    Filters the aggregator's records to the ones tagged ``ep=episode_index``,
    builds a summary + verdict, appends a JSON line to
    ``<dataset.root>/meta/episodes_health.jsonl``, and logs a verdict
    line at INFO (healthy) or WARNING (issues). Intentionally cheap —
    no expensive recomputation, no extra I/O on the loop path.
    """
    from lerobot.utils.latency.recording_health import (
        filter_by_episode,
        summarize,
        verdict,
    )

    target_period_ms = 1000.0 / float(fps)
    ep_records = filter_by_episode(list(latency_session.aggregator._records), episode_index)
    if not ep_records:
        return
    summary = summarize(ep_records, target_period_ms=target_period_ms)
    summary["episode_index"] = episode_index
    health = verdict(summary)
    summary["healthy"] = health["healthy"]
    summary["issues"] = health["issues"]

    meta_dir = dataset.root / "meta"
    meta_dir.mkdir(parents=True, exist_ok=True)
    out_path = meta_dir / "episodes_health.jsonl"
    with open(out_path, "a", encoding="utf-8") as f:
        f.write(json.dumps(summary, separators=(",", ":")) + "\n")

    if health["healthy"]:
        logging.info(
            "Episode %d health: OK (%.1f%% overrun, loop_dt p95=%.1fms)",
            episode_index,
            summary["overrun_ratio"] * 100,
            summary["loop_dt_ms"]["p95"],
        )
    else:
        issue_str = "; ".join(f"{i['rule']}: {i['message']}" for i in health["issues"])
        logging.warning(
            "Episode %d health: UNHEALTHY — %s. See meta/episodes_health.jsonl.",
            episode_index,
            issue_str,
        )


def _write_recording_health(
    latency_session: LatencySession,
    dataset: LeRobotDataset,
    fps: int,
) -> None:
    """Persist the aggregate quality summary for the whole recording session.

    Distinct from ``_write_episode_health`` in two ways: (1) it covers
    every iteration in the aggregator, not one episode's slice; (2) it
    writes a single JSON file rather than appending a line, so the data
    panel can read it as the "did this session record cleanly?" verdict
    without scanning every episode line.
    """
    from lerobot.utils.latency.recording_health import summarize, verdict

    target_period_ms = 1000.0 / float(fps)
    all_records = list(latency_session.aggregator._records)
    if not all_records:
        return
    summary = summarize(all_records, target_period_ms=target_period_ms)
    health = verdict(summary)
    summary["healthy"] = health["healthy"]
    summary["issues"] = health["issues"]
    summary["loop_kind"] = latency_session.loop_kind

    meta_dir = dataset.root / "meta"
    meta_dir.mkdir(parents=True, exist_ok=True)
    # Atomic write so a crash during the final dump doesn't leave a
    # half-written `recording_health.json` that confuses the GUI's
    # dataset-health banner on next open.
    import os

    out_path = meta_dir / "recording_health.json"
    tmp_path = out_path.with_suffix(out_path.suffix + ".tmp")
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, separators=(",", ":"))
    os.replace(tmp_path, out_path)


@safe_stop_image_writer
def record_loop(
    robot: Robot,
    events: dict,
    fps: int,
    teleop_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs after teleop
    robot_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs before robot
    robot_observation_processor: RobotProcessorPipeline[
        RobotObservation, RobotObservation
    ],  # runs after robot
    dataset: LeRobotDataset | None = None,
    intervention_dataset: LeRobotDataset | None = None,
    teleop: Teleoperator | list[Teleoperator] | None = None,
    policy: PreTrainedPolicy | None = None,
    preprocessor: PolicyProcessorPipeline[dict[str, Any], dict[str, Any]] | None = None,
    postprocessor: PolicyProcessorPipeline[PolicyAction, PolicyAction] | None = None,
    control_time_s: int | None = None,
    single_task: str | None = None,
    display_data: bool = False,
    interpolator: ActionInterpolator | None = None,
    display_mode: str = "rerun",
    display_compressed_images: bool = False,
    play_sounds: bool = True,
    latency_session: LatencySession | None = None,
    episode_index: int | None = None,
) -> list[dict]:
    if dataset is not None and dataset.fps != fps:
        raise ValueError(f"The dataset fps should be equal to requested fps ({dataset.fps} != {fps}).")

    teleop_arm = teleop_keyboard = None
    if isinstance(teleop, list):
        teleop_keyboard = next((t for t in teleop if isinstance(t, KeyboardTeleop)), None)
        teleop_arm = next(
            (
                t
                for t in teleop
                if isinstance(
                    t,
                    (
                        so_leader.SO100Leader
                        | so_leader.SO101Leader
                        | koch_leader.KochLeader
                        | omx_leader.OmxLeader
                    ),
                )
            ),
            None,
        )

        if not (teleop_arm and teleop_keyboard and len(teleop) == 2 and robot.name == "lekiwi_client"):
            raise ValueError(
                "For multi-teleop, the list must contain exactly one KeyboardTeleop and one arm teleoperator. Currently only supported for LeKiwi robot."
            )

    # Reset policy and processor if they are provided
    if policy is not None and preprocessor is not None and postprocessor is not None:
        policy.reset()
        preprocessor.reset()
        postprocessor.reset()

    # Reset interpolator if provided
    if interpolator is not None:
        interpolator.reset()

    # Calculate control interval based on interpolation
    use_interpolation = interpolator is not None and interpolator.enabled and policy is not None
    control_interval = interpolator.get_control_interval(fps) if interpolator else 1 / fps
    # Pre-compute action key order outside the hot loop — it won't change mid-episode.
    action_keys = sorted(robot.action_features) if use_interpolation else []

    no_action_count = 0

    # Reset intervention state for new episode
    if teleop is not None and hasattr(teleop, "reset_intervention"):
        teleop.reset_intervention()

    # Reset intervention buffer with correct episode_index for this main episode
    # (buffer created at end of previous record_loop has stale episode_index)
    if intervention_dataset is not None:
        intervention_dataset.writer.episode_buffer = intervention_dataset.writer._create_episode_buffer()

    # Track intervention state for transition detection
    was_intervening = False
    # Track last follower position sent to leader (for servo compensation on intervention)
    last_follower_pos_sent: dict[str, float] = {}

    # Collect intervention episode buffers for deferred saving (avoids mid-episode lag)
    pending_intervention_episodes: list[dict] = []

    if latency_session is None:
        latency_session = LatencySession.disabled()

    timestamp = 0
    start_episode_t = time.perf_counter()
    while timestamp < control_time_s:
        start_loop_t = time.perf_counter()
        latency_session.start_iter()
        # Tag every record with the episode index so the post-episode
        # quality summary can filter records by ``ep`` and the data panel
        # can render per-episode badges from meta/episodes_health.jsonl.
        # ``None`` for reset / non-episode phases — those records are
        # excluded from any episode's verdict.
        if episode_index is not None:
            latency_session.set_field("ep", episode_index)

        if events["exit_early"]:
            events["exit_early"] = False
            break
        # File-backed teleops (trajectory_replay) flip ``is_exhausted``
        # once the recorded trajectory has fully played out. Treat that as
        # a clean end-of-episode signal — the calling driver will then
        # enter the reset phase as usual.
        if teleop is not None and getattr(teleop, "is_exhausted", False):
            break

        # Get robot observation. The span includes follower sync_read +
        # cached cam.read_latest() per camera (cameras are microseconds-fast
        # because grab threads cache them; the time is dominated by the
        # motor sync_read).
        with latency_session.span("get_observation"):
            obs = robot.get_observation()

        # Per-camera staleness/period — read latest_timestamp from each
        # camera right after get_observation. No-op when session is disabled.
        latency_session.cam_consume_all(getattr(robot, "cameras", None))

        # Applies a pipeline to the raw robot observation, default is IdentityProcessor
        with latency_session.span("process_obs"):
            obs_processed = robot_observation_processor(obs)

        if policy is not None or dataset is not None or intervention_dataset is not None:
            # Use main dataset features (intervention_dataset has the same features)
            features = dataset.features if dataset is not None else intervention_dataset.features
            observation_frame = build_dataset_frame(features, obs_processed, prefix=OBS_STR)

        # The action-selection block below has many branches (policy with /
        # without interpolation, intervention, teleop-only, dual teleop, no-op).
        # We time the whole thing as a single ``process_action`` span via
        # add_span so we don't have to wrap each branch in its own ``with``.
        # ``continue``s inside the branches simply skip the rest of this
        # iteration (which means they skip end_iter() too — that's fine,
        # the next start_iter() resets the tracer state cleanly).
        process_action_t0 = time.perf_counter()

        # Check for intervention if teleop supports it (only during main recording with policy)
        # Skip during reset phase (intervention_dataset is None) to avoid confusing behavior
        is_intervention = False
        if intervention_dataset is not None and teleop is not None and hasattr(teleop, "get_teleop_events"):
            teleop_events = teleop.get_teleop_events()
            is_intervention = teleop_events.get(TeleopEvents.IS_INTERVENTION, False)

        # Track whether this iteration should be recorded to the dataset.
        # Interpolated-only iterations send actions to the robot but don't record frames,
        # keeping the dataset at the original fps while the robot moves at the higher rate.
        is_record_frame = True

        # Get action from policy, teleop, or intervention
        if (
            policy is not None
            and preprocessor is not None
            and postprocessor is not None
            and not is_intervention
        ):
            # Transition: intervention → policy (user pressed SPACE again)
            if was_intervening:
                # Defer saving: copy buffer now, save all at end of main episode (avoids lag)
                if (
                    intervention_dataset is not None
                    and intervention_dataset.writer.episode_buffer is not None
                    and intervention_dataset.writer.episode_buffer.get("size", 0) > 0
                ):
                    pending_intervention_episodes.append(
                        copy.deepcopy(intervention_dataset.writer.episode_buffer)
                    )
                    # Reset buffer for next intervention, pre-assign episode_index to avoid collision
                    intervention_dataset.writer.episode_buffer = (
                        intervention_dataset.writer._create_episode_buffer()
                    )
                    next_ep_idx = intervention_dataset.num_episodes + len(pending_intervention_episodes)
                    intervention_dataset.writer.episode_buffer["episode_index"] = next_ep_idx

                policy.reset()
                preprocessor.reset()
                postprocessor.reset()
                if teleop is not None and hasattr(teleop, "enable_torque"):
                    try:
                        teleop.enable_torque()
                    except ConnectionError as e:
                        logging.warning(
                            f"Failed to enable torque on leader: {e}. Release the arm and try again."
                        )
                log_say("Policy", play_sounds)

            # With interpolation: only call policy when interpolator needs new action
            if use_interpolation:
                ran_inference = False

                if interpolator.needs_new_action():
                    with latency_session.span("inference"):
                        action_values = predict_action(
                            observation=observation_frame,
                            policy=policy,
                            device=get_safe_torch_device(policy.config.device),
                            preprocessor=preprocessor,
                            postprocessor=postprocessor,
                            use_amp=policy.config.use_amp,
                            task=single_task,
                            robot_type=robot.robot_type,
                        )
                    act_processed_policy = make_robot_action(action_values, dataset.features)
                    robot_action_to_send = robot_action_processor((act_processed_policy, obs))

                    action_tensor = torch.tensor([robot_action_to_send[k] for k in action_keys])
                    interpolator.add(action_tensor)
                    ran_inference = True

                interp_action = interpolator.get()
                if interp_action is not None:
                    robot_action_to_send = {k: interp_action[i].item() for i, k in enumerate(action_keys)}
                    action_values = robot_action_to_send
                else:
                    continue

                is_record_frame = ran_inference
            else:
                with latency_session.span("inference"):
                    action_values = predict_action(
                        observation=observation_frame,
                        policy=policy,
                        device=get_safe_torch_device(policy.config.device),
                        preprocessor=preprocessor,
                        postprocessor=postprocessor,
                        use_amp=policy.config.use_amp,
                        task=single_task,
                        robot_type=robot.robot_type,
                    )
                act_processed_policy: RobotAction = make_robot_action(action_values, dataset.features)
                # Applies a pipeline to the action, default is IdentityProcessor
                robot_action_to_send = robot_action_processor((act_processed_policy, obs))
                action_values = robot_action_to_send

            # Inverse-follow: send follower position to leader, compensating for
            # servo tracking error so the leader is always close to the follower.
            if teleop is not None and hasattr(teleop, "send_feedback"):
                follower_pos = {k: v for k, v in obs.items() if k.endswith(".pos")}
                leader_actual = teleop.get_action()
                compensated = {}
                correction_gain = 0.3  # 0-1: lower = smoother but slower convergence
                for k, target in follower_pos.items():
                    error = leader_actual.get(k, target) - target
                    compensated[k] = target - correction_gain * error
                teleop.send_feedback(compensated)
                last_follower_pos_sent = follower_pos

        elif is_intervention and teleop is not None:
            # Human intervention mode
            if not was_intervening:
                # Transition: policy → intervention
                # Compensate servo tracking error before releasing torque:
                # The leader servo can't perfectly reach its goal under load.
                # Measure the error, overshoot the goal by that amount, wait for
                # the servo to settle at the correct position, then release.
                if last_follower_pos_sent and hasattr(teleop, "send_feedback"):
                    target = last_follower_pos_sent
                    # Start with current goal, iteratively adjust
                    goal = dict(target)

                    # Iterative compensation loop with audio feedback.
                    # Each iteration: measure where the servo actually is,
                    # adjust the goal to push it closer to target.
                    settle_tolerance = 1.0  # normalized units
                    sync_timeout = 5.0  # seconds - avoid infinite beep loop if servo can't converge
                    sync_start = time.perf_counter()
                    beep_proc = None
                    try:
                        while True:
                            pos = teleop.get_action()
                            max_err = max(abs(pos.get(k, 0) - target[k]) for k in target)
                            if max_err < settle_tolerance:
                                break

                            if time.perf_counter() - sync_start > sync_timeout:
                                logging.warning(
                                    f"Servo sync timed out after {sync_timeout}s (max_err={max_err:.2f}), "
                                    "releasing torque anyway"
                                )
                                break

                            # Adjust goal: for each joint, nudge goal by remaining error
                            for k in target:
                                error = pos.get(k, 0) - target[k]
                                goal[k] = goal[k] - error
                            teleop.send_feedback(goal)

                            # Audio feedback: beeps when far, continuous tone when close
                            almost_ready = max_err < settle_tolerance * 2
                            if almost_ready:
                                # Continuous high tone = "hold steady, almost there!"
                                # Only start if not already playing
                                if beep_proc is None or beep_proc.poll() is not None:
                                    sr = 8000
                                    dur = 1.0  # long tone, will be killed on convergence
                                    t = np.linspace(0, dur, int(sr * dur), dtype=np.float32)
                                    tone = (np.sin(2 * np.pi * 1000 * t) * 16000).astype(np.int16)
                                    beep_proc = subprocess.Popen(
                                        ["aplay", "-f", "S16_LE", "-r", str(sr), "-c", "1", "-q"],
                                        stdin=subprocess.PIPE,
                                        stderr=subprocess.DEVNULL,
                                    )
                                    beep_proc.stdin.write(tone.tobytes())
                                    beep_proc.stdin.close()
                                time.sleep(0.05)
                            else:
                                # Kill continuous tone if we regressed
                                if beep_proc is not None and beep_proc.poll() is None:
                                    beep_proc.terminate()
                                    beep_proc = None
                                # Intermittent beeps: large error → fast, small error → slow
                                interval = min(0.5, max(0.05, 0.05 + 0.45 * (1 - max_err / 50)))
                                if beep_proc is None or beep_proc.poll() is not None:
                                    sr = 8000
                                    dur = min(interval * 0.6, 0.08)
                                    t = np.linspace(0, dur, int(sr * dur), dtype=np.float32)
                                    freq = 600 + min(max_err, 50) * 8  # 600-1000Hz
                                    tone = (np.sin(2 * np.pi * freq * t) * 16000).astype(np.int16)
                                    beep_proc = subprocess.Popen(
                                        ["aplay", "-f", "S16_LE", "-r", str(sr), "-c", "1", "-q"],
                                        stdin=subprocess.PIPE,
                                        stderr=subprocess.DEVNULL,
                                    )
                                    beep_proc.stdin.write(tone.tobytes())
                                    beep_proc.stdin.close()
                                time.sleep(interval)
                    finally:
                        # Always terminate any outstanding beep — both the
                        # normal break paths above AND any exception from
                        # teleop.get_action / send_feedback inside the loop
                        # would otherwise leave `aplay` running until the
                        # parent process exits.
                        if beep_proc is not None and beep_proc.poll() is None:
                            beep_proc.terminate()

                    settle_ms = (time.perf_counter() - start_loop_t) * 1e3
                    logging.info(f"Servo compensation converged in {settle_ms:.0f}ms (max_err={max_err:.2f})")

                if hasattr(teleop, "disable_torque"):
                    teleop.disable_torque()

                log_say("Intervention", play_sounds)

            act = teleop.get_action()
            act_processed_teleop = teleop_action_processor((act, obs))
            action_values = act_processed_teleop
            robot_action_to_send = robot_action_processor((act_processed_teleop, obs))

            # Record to intervention dataset (correction data)
            if intervention_dataset is not None:
                int_action_frame = build_dataset_frame(
                    intervention_dataset.features, act_processed_teleop, prefix=ACTION
                )
                int_frame = {**observation_frame, **int_action_frame, "task": single_task}
                intervention_dataset.add_frame(int_frame)

        elif policy is None and isinstance(teleop, Teleoperator):
            act = teleop.get_action()
            if robot.name == "unitree_g1":
                teleop.send_feedback(obs)

            # Applies a pipeline to the raw teleop action, default is IdentityProcessor
            act_processed_teleop = teleop_action_processor((act, obs))
            action_values = act_processed_teleop
            robot_action_to_send = robot_action_processor((act_processed_teleop, obs))

        elif policy is None and isinstance(teleop, list):
            arm_action = teleop_arm.get_action()
            arm_action = {f"arm_{k}": v for k, v in arm_action.items()}
            keyboard_action = teleop_keyboard.get_action()
            base_action = robot._from_keyboard_to_base_action(keyboard_action)
            act = {**arm_action, **base_action} if len(base_action) > 0 else arm_action
            act_processed_teleop = teleop_action_processor((act, obs))
            action_values = act_processed_teleop
            robot_action_to_send = robot_action_processor((act_processed_teleop, obs))
        else:
            no_action_count += 1
            if no_action_count == 1 or no_action_count % 10 == 0:
                logging.warning(
                    "No policy or teleoperator provided, skipping action generation. "
                    "This is likely to happen when resetting the environment without a teleop device. "
                    "The robot won't be at its rest position at the start of the next episode."
                )
            continue

        # Close the process_action span here — by this point an action
        # was selected from one of the branches above. Iterations that
        # `continue`d above never reach end_iter() and are silently
        # dropped (next start_iter() resets), which is the right behavior.
        latency_session.add_span("process_action", process_action_t0)

        # Send action to robot
        # Action can eventually be clipped using `max_relative_target`,
        # so action actually sent is saved in the dataset. action = postprocessor.process(action)
        # TODO(steven, pepijn, adil): we should use a pipeline step to clip the action, so the sent action is the action that we input to the robot.
        # Chunk-aware path: if the teleop publishes a future horizon, the
        # chunk goes to the robot verbatim so chunk-aware robots can do
        # exact-lookup motor-τ compensation. The dict-shaped
        # robot_action_to_send is the back-compat fallback (and the
        # already-recorded action_values matches its frames[0] by contract).
        # Only applies when teleop is a single Teleoperator (the policy /
        # composite-teleop branches don't have a teleop instance to query).
        action_to_send = robot_action_to_send
        if isinstance(teleop, Teleoperator):
            horizon = teleop.get_action_with_horizon()
            if horizon is not None:
                action_to_send = horizon
        with latency_session.span("action_send"):
            _sent_action = robot.send_action(action_to_send)

        # Write to dataset (only on real policy frames, not interpolated-only iterations)
        if dataset is not None and is_record_frame:
            with latency_session.span("dataset_write"):
                action_frame = build_dataset_frame(dataset.features, action_values, prefix=ACTION)
                frame = {**observation_frame, **action_frame, "task": single_task}
                dataset.add_frame(frame)

        if display_data:
            log_visualization_data(
                display_mode,
                observation=obs_processed,
                action=action_values,
                compress_images=display_compressed_images,
            )

        # Commit BEFORE precise_sleep so loop_dt_ms reflects iteration *work*
        # time, not work + sleep — same rationale as teleop_loop.
        # end_iter() also throttle-publishes the snapshot + 1 Hz log line.
        latency_session.end_iter()

        dt_s = time.perf_counter() - start_loop_t

        sleep_time_s: float = control_interval - dt_s
        if sleep_time_s < 0:
            logging.warning(
                f"Record loop is running slower ({1 / dt_s:.1f} Hz) than the target FPS ({fps} Hz). Dataset frames might be dropped and robot control might be unstable. Common causes are: 1) Camera FPS not keeping up 2) Policy inference taking too long 3) CPU starvation"
            )

        precise_sleep(max(sleep_time_s, 0.0))

        # Update intervention tracking for next iteration
        was_intervening = is_intervention

        timestamp = time.perf_counter() - start_episode_t

    # Collect pending intervention episodes to return (saved after main episode)
    if intervention_dataset is not None:
        # Add current buffer to pending if it has frames (intervention was active at episode end)
        if (
            intervention_dataset.writer.episode_buffer is not None
            and intervention_dataset.writer.episode_buffer.get("size", 0) > 0
        ):
            pending_intervention_episodes.append(copy.deepcopy(intervention_dataset.writer.episode_buffer))
            intervention_dataset.writer.episode_buffer = intervention_dataset.writer._create_episode_buffer()

        # On re-record, discard and reset buffer for next attempt
        if events.get("rerecord_episode", False):
            if pending_intervention_episodes:
                logging.info(
                    f"Discarding {len(pending_intervention_episodes)} intervention episode(s) for re-record"
                )
            pending_intervention_episodes = []
            intervention_dataset.writer.episode_buffer = intervention_dataset.writer._create_episode_buffer()

    return pending_intervention_episodes


@parser.wrap()
def record(cfg: RecordConfig) -> LeRobotDataset:
    setup_run_logging(cfg.latency_output_dir, "record")
    logging.info(pformat(asdict(cfg)))
    if cfg.display_data:
        init_visualization(
            cfg.display_mode, session_name="recording", ip=cfg.display_ip, port=cfg.display_port
        )
    _is_remote = cfg.display_ip is not None and cfg.display_ip not in ("127.0.0.1", "localhost", "::1")
    display_compressed_images = (
        True
        if (cfg.display_data and _is_remote and cfg.display_port is not None)
        else cfg.display_compressed_images
    )

    robot = make_robot_from_config(cfg.robot)
    teleop = make_teleoperator_from_config(cfg.teleop) if cfg.teleop is not None else None

    teleop_action_processor, robot_action_processor, robot_observation_processor = make_default_processors()

    # Add custom observation processor steps from the robot
    custom_steps = robot.get_observation_processor_steps()
    if custom_steps:
        # Insert custom steps at the beginning of the pipeline
        robot_observation_processor.steps = custom_steps + robot_observation_processor.steps
        logging.info(f"Added {len(custom_steps)} custom observation processor step(s) from robot")

    # Append obs stream writer as the last step (writes processed obs to shared memory)
    from lerobot.robots.obs_stream import make_obs_stream_writer_step

    obs_stream_step = make_obs_stream_writer_step()
    if obs_stream_step is not None:
        robot_observation_processor.steps.append(obs_stream_step)

    dataset_features = combine_feature_dicts(
        aggregate_pipeline_dataset_features(
            pipeline=teleop_action_processor,
            initial_features=create_initial_features(
                action=robot.action_features
            ),  # TODO(steven, pepijn): in future this should be come from teleop or policy
            use_videos=cfg.dataset.video,
        ),
        aggregate_pipeline_dataset_features(
            pipeline=robot_observation_processor,
            initial_features=create_initial_features(observation=robot.observation_features),
            use_videos=cfg.dataset.video,
        ),
    )

    dataset = None
    intervention_dataset = None
    listener = None
    # Initialise latency_session up-front so the ``finally`` block can
    # reference it even if a setup step (robot.connect / make_policy /
    # ...) raises before the real session is constructed below.
    latency_session: LatencySession = LatencySession.disabled()

    try:
        if cfg.resume:
            num_cameras = len(robot.cameras) if hasattr(robot, "cameras") else 0
            dataset = LeRobotDataset.resume(
                cfg.dataset.repo_id,
                root=cfg.dataset.root,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                rgb_encoder=cfg.dataset.rgb_encoder,
                depth_encoder=cfg.dataset.depth_encoder,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
                record_images=cfg.dataset.record_images,
                image_writer_processes=cfg.dataset.num_image_writer_processes
                if cfg.dataset.record_images and num_cameras > 0
                else 0,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * num_cameras
                if cfg.dataset.record_images and num_cameras > 0
                else 0,
            )
            sanity_check_dataset_robot_compatibility(dataset, robot, cfg.dataset.fps, dataset_features)
        else:
            # Create empty dataset or load existing saved episodes
            sanity_check_dataset_name(cfg.dataset.repo_id, cfg.policy)
            dataset = LeRobotDataset.create(
                cfg.dataset.repo_id,
                cfg.dataset.fps,
                root=cfg.dataset.root,
                robot_type=robot.name,
                features=dataset_features,
                use_videos=cfg.dataset.video,
                image_writer_processes=cfg.dataset.num_image_writer_processes
                if cfg.dataset.record_images
                else 0,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras)
                if cfg.dataset.record_images
                else 0,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                rgb_encoder=cfg.dataset.rgb_encoder,
                depth_encoder=cfg.dataset.depth_encoder,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
                record_images=cfg.dataset.record_images,
            )

        # Create or resume intervention dataset if requested (for correction data)
        if cfg.intervention_repo_id is not None:
            if cfg.resume:
                num_cameras = len(robot.cameras) if hasattr(robot, "cameras") else 0
                intervention_dataset = LeRobotDataset.resume(
                    cfg.intervention_repo_id,
                    root=cfg.dataset.root,
                    batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                    rgb_encoder=cfg.dataset.rgb_encoder,
                    depth_encoder=cfg.dataset.depth_encoder,
                    image_writer_processes=cfg.dataset.num_image_writer_processes if num_cameras > 0 else 0,
                    image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * num_cameras
                    if num_cameras > 0
                    else 0,
                )
                logging.info(
                    f"Resumed intervention dataset: {cfg.intervention_repo_id} ({intervention_dataset.num_episodes} episodes)"
                )
            else:
                intervention_dataset = LeRobotDataset.create(
                    cfg.intervention_repo_id,
                    cfg.dataset.fps,
                    root=cfg.dataset.root,
                    robot_type=robot.name,
                    features=dataset_features,
                    use_videos=cfg.dataset.video,
                    image_writer_processes=cfg.dataset.num_image_writer_processes,
                    image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                    batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                    rgb_encoder=cfg.dataset.rgb_encoder,
                    depth_encoder=cfg.dataset.depth_encoder,
                )
                logging.info(f"Created intervention dataset: {cfg.intervention_repo_id}")

        # Load pretrained policy
        policy = (
            None
            if cfg.policy is None
            else make_policy(cfg.policy, ds_meta=dataset.meta, rename_map=cfg.dataset.rename_map)
        )
        preprocessor = None
        postprocessor = None
        interpolator = None
        if cfg.policy is not None:
            # Advisory: surface embodiment mismatch (e.g. policy trained on
            # bi_so107_follower running on bi_so107_follower_predictive).
            # Doesn't block; prompts interactively if the TTY allows.
            warn_on_policy_robot_type_mismatch(cfg.policy.pretrained_path, robot)
            preprocessor, postprocessor = make_pre_post_processors(
                policy_cfg=cfg.policy,
                pretrained_path=cfg.policy.pretrained_path,
                dataset_stats=rename_stats(dataset.meta.stats, cfg.dataset.rename_map),
                preprocessor_overrides={
                    "device_processor": {"device": cfg.policy.device},
                    "rename_observations_processor": {"rename_map": cfg.dataset.rename_map},
                },
            )
            # Create interpolator for smoother policy control
            if cfg.interpolation_multiplier > 1:
                interpolator = ActionInterpolator(multiplier=cfg.interpolation_multiplier)
                logging.info(f"Action interpolation enabled: {cfg.interpolation_multiplier}x control rate")

        robot.connect()
        if teleop is not None:
            teleop.connect()
            # Predictive / chunk-aware robots can poll teleop.get_action()
            # at their own control rate. Default no-op for plain robots.
            # See SO107FollowerPredictive.attach_teleop for details.
            robot.attach_teleop(teleop)

        listener, events = init_keyboard_listener()

        latency_session = LatencySession.from_config(
            enabled=cfg.latency_monitor,
            loop_kind="record",
            target_fps=float(cfg.dataset.fps),
            output_dir=cfg.latency_output_dir if cfg.latency_monitor else None,
        )
        if latency_session.enabled and latency_session.writer is not None:
            logging.info("Latency monitoring enabled; snapshots → %s", latency_session.writer.path)
            # Attribute the umbrella ``process_obs`` cost back to per-step
            # spans so the snapshot shows which processor (depth-edge,
            # obs-stream writer, normalize, …) eats the budget.
            from lerobot.utils.latency import attach_pipeline_step_spans

            attach_pipeline_step_spans(robot_observation_processor, latency_session, prefix="obs")

        if not cfg.dataset.streaming_encoding:
            logging.info(
                "Streaming encoding is disabled. If you have capable hardware, consider enabling it for way faster episode saving. --dataset.streaming_encoding=true --dataset.encoder_threads=2 # --dataset.rgb_encoder.vcodec=auto. More info in the documentation: https://huggingface.co/docs/lerobot/streaming_video_encoding"
            )

        def run_reset_phase():
            """Run a reset phase to allow setting up / resetting the environment.

            For human-driven teleops this is "free teleop for reset_time_s
            seconds while the operator rearranges objects". For file-backed
            teleops (e.g. ``trajectory_replay``), it instead programmatically
            drives the robot back to the trajectory's start pose and re-arms
            the teleop so the next episode can begin.
            """
            # File-backed (episodic) teleop: skip the manual record_loop
            # reset — that path would just spin against an exhausted
            # teleop. Drive the arm back to the trajectory's start pose
            # and re-arm. Duck-typed via ``start_pose`` so any future
            # episodic teleop only needs to expose that property.
            if teleop is not None and hasattr(teleop, "start_pose"):
                from lerobot.robots.rest_position import move_to_rest_position

                log_say("Auto-reset: moving to trajectory start", cfg.play_sounds)
                if getattr(teleop, "is_exhausted", False):
                    teleop.disconnect()
                    teleop.connect()
                move_to_rest_position(robot, teleop.start_pose, duration_s=cfg.auto_reset_duration_s)
                return

            # Always disable torque on leader for reset phase so operator can teleop freely
            # (regardless of whether the previous episode ended with intervention or policy)
            if teleop is not None and hasattr(teleop, "disable_torque"):
                teleop.disable_torque()
            log_say("Reset the environment", cfg.play_sounds)

            if robot.name == "unitree_g1":
                robot.reset()

            record_loop(
                robot=robot,
                events=events,
                fps=cfg.dataset.fps,
                teleop_action_processor=teleop_action_processor,
                robot_action_processor=robot_action_processor,
                robot_observation_processor=robot_observation_processor,
                teleop=teleop,
                control_time_s=cfg.dataset.reset_time_s,
                single_task=cfg.dataset.single_task,
                display_data=cfg.display_data,
                display_mode=cfg.display_mode,
                latency_session=latency_session,
            )

        dataset_ctx = VideoEncodingManager(dataset) if cfg.dataset.record_images else nullcontext()
        with dataset_ctx:
            # Use nested context manager for intervention dataset if it exists
            intervention_ctx = (
                VideoEncodingManager(intervention_dataset) if intervention_dataset else nullcontext()
            )
            with intervention_ctx:
                recorded_episodes = 0

                # For file-backed teleops, ALWAYS do an initial move-to-start
                # so episode 1's first emitted frame doesn't teleport the
                # robot from wherever it happens to be at launch time. The
                # ``start_with_reset`` flag is honoured for the human flow.
                _is_episodic_teleop = teleop is not None and hasattr(teleop, "start_pose")
                if not events["stop_recording"] and (cfg.start_with_reset or _is_episodic_teleop):
                    run_reset_phase()

                while recorded_episodes < cfg.dataset.num_episodes and not events["stop_recording"]:
                    current_episode_index = dataset.num_episodes
                    log_say(f"Recording episode {current_episode_index}", cfg.play_sounds)
                    pending_intervention_episodes = record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop_action_processor=teleop_action_processor,
                        robot_action_processor=robot_action_processor,
                        robot_observation_processor=robot_observation_processor,
                        teleop=teleop,
                        policy=policy,
                        preprocessor=preprocessor,
                        postprocessor=postprocessor,
                        dataset=dataset,
                        intervention_dataset=intervention_dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                        interpolator=interpolator,
                        display_mode=cfg.display_mode,
                        display_compressed_images=display_compressed_images,
                        play_sounds=cfg.play_sounds,
                        latency_session=latency_session,
                        episode_index=current_episode_index,
                    )

                    import time as _time

                    _t_between = _time.monotonic()

                    # Execute a few seconds without recording to give time to manually reset the environment
                    # Skip reset for the last episode to be recorded.
                    # Exception: episodic teleops (trajectory_replay) always
                    # park the arm at trajectory-start so the recorded
                    # endpoint can't sag under gravity at disconnect.
                    if not events["stop_recording"] and (
                        (recorded_episodes < cfg.dataset.num_episodes - 1)
                        or events["rerecord_episode"]
                        or _is_episodic_teleop
                    ):
                        run_reset_phase()

                    _t_after_reset = _time.monotonic()

                    if events["rerecord_episode"]:
                        log_say("Re-record episode", cfg.play_sounds)
                        events["rerecord_episode"] = False
                        events["exit_early"] = False
                        dataset.clear_episode_buffer()
                        # pending_intervention_episodes already cleared in record_loop
                        continue

                    dataset.save_episode()

                    # Per-episode quality summary — append to
                    # meta/episodes_health.jsonl so the data panel can
                    # render badges next to bad episodes, and log a one-
                    # line verdict so headless operators see it in stderr.
                    # Live warnings already fired during recording via
                    # LoopHealthDetector; this is the persistent record.
                    # Best-effort: catch ANY failure (incl. a
                    # ZeroDivisionError when the loop was so badly stalled
                    # that all per-frame periods are zero) so a degenerate
                    # metric can't abort the actual recording. Symmetric
                    # with the final-summary call below at line ~1248.
                    if latency_session.enabled and latency_session.aggregator is not None:
                        try:
                            _write_episode_health(
                                latency_session,
                                dataset,
                                current_episode_index,
                                cfg.dataset.fps,
                            )
                        except Exception as e:  # noqa: BLE001
                            logging.warning(
                                "Could not write episode %d health: %s",
                                current_episode_index,
                                e,
                            )

                    # Save intervention episodes AFTER main episode (ensures matching)
                    if intervention_dataset is not None and pending_intervention_episodes:
                        for ep_buffer in pending_intervention_episodes:
                            intervention_dataset.save_episode(episode_data=ep_buffer)
                            logging.info(
                                f"Saved intervention episode {intervention_dataset.num_episodes - 1}"
                            )
                        # Restart video encoders for the next intervention episode.
                        # save_episode(episode_data=...) skips clear_episode_buffer(),
                        # so encoders are left in a finished state.
                        if intervention_dataset.writer.video_encoders:
                            intervention_dataset.writer.episode_buffer = (
                                intervention_dataset.writer._create_episode_buffer()
                            )
                            intervention_dataset.writer._start_video_encoders()

                    _t_after_save = _time.monotonic()
                    logging.info(
                        f"between-episode timing: reset_phase={_t_after_reset - _t_between:.1f}s, "
                        f"save_episode={_t_after_save - _t_after_reset:.1f}s, "
                        f"total={_t_after_save - _t_between:.1f}s"
                    )
                    recorded_episodes += 1
    finally:
        log_say("Stop recording", cfg.play_sounds, blocking=True)

        # Aggregate quality summary for the whole recording session.
        # Written before dataset.finalize() so the file lands alongside
        # episodes_health.jsonl in meta/. Best-effort: swallow any
        # filesystem hiccup so it can't mask the actual recording result.
        if dataset is not None and latency_session.enabled and latency_session.aggregator is not None:
            try:
                _write_recording_health(latency_session, dataset, cfg.dataset.fps)
            except Exception as e:  # noqa: BLE001
                logging.warning("Could not write recording_health.json: %s", e)

        if dataset:
            dataset.finalize()

        if intervention_dataset:
            intervention_dataset.finalize()
            logging.info(f"Intervention dataset contains {intervention_dataset.num_episodes} episodes")

        if robot.is_connected:
            robot.disconnect()
        if teleop and teleop.is_connected:
            teleop.disconnect()

        if not is_headless() and listener:
            listener.stop()

        if cfg.display_data:
            shutdown_visualization(cfg.display_mode)

        if cfg.dataset.push_to_hub:
            if dataset and dataset.num_episodes > 0:
                dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)
            else:
                logging.warning("No episodes saved — skipping push to hub")

        if intervention_dataset and cfg.dataset.push_to_hub:
            intervention_dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)

        log_say("Exiting", cfg.play_sounds)
    return dataset


